-- LA 2 Oil & Lube shop app — database schema.
-- Paste into the Supabase SQL editor (Dashboard → SQL Editor → New query) and run once.
-- Safe to re-run on an empty project; it does not drop anything.

-- ---------------------------------------------------------------------------
-- Who may use the app
-- ---------------------------------------------------------------------------
-- Only logins listed here can read or write shop data. Even if public sign-ups
-- were left on by accident, a stranger's account sees nothing.
create table if not exists public.shop_users (
  user_id  uuid primary key references auth.users (id) on delete cascade,
  added_at timestamptz not null default now()
);
alter table public.shop_users enable row level security;
-- (No policies: the table is managed from the dashboard only.)

create or replace function public.is_shop_user()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.shop_users where user_id = auth.uid());
$$;

-- ---------------------------------------------------------------------------
-- Customers and vehicles
-- ---------------------------------------------------------------------------
create table if not exists public.customers (
  id           uuid primary key default gen_random_uuid(),
  name         text not null,
  phone        text not null default '',
  -- Set when a customer is imported from DataLube, so re-running an import doesn't duplicate.
  datalube_id  text unique,
  created_at   timestamptz not null default now()
);

create table if not exists public.vehicles (
  id           uuid primary key default gen_random_uuid(),
  customer_id  uuid not null references public.customers (id) on delete cascade,
  year         integer,
  make         text not null default '',
  model        text not null default '',
  engine       text not null default '',
  plate        text not null default '',
  datalube_id  text unique,
  created_at   timestamptz not null default now()
);
create index if not exists vehicles_customer_id_idx on public.vehicles (customer_id);

-- ---------------------------------------------------------------------------
-- Tickets: one row per visit. Bay board, payment, history and reports all read this.
-- ---------------------------------------------------------------------------
create table if not exists public.tickets (
  id              uuid primary key default gen_random_uuid(),
  invoice_number  bigint generated by default as identity (start with 1001) unique,
  customer_id     uuid not null references public.customers (id),
  vehicle_id      uuid not null references public.vehicles (id),
  customer_name   text not null,
  vehicle_label   text not null,
  mileage         integer not null check (mileage >= 0),
  -- [{ "id": "oil-synthetic", "name": "Full Synthetic Oil Change", "price": 74.99, "category": "oilchange" }, ...]
  lines           jsonb not null default '[]'::jsonb,
  status          text not null default 'waiting'
                    check (status in ('waiting', 'in_progress', 'ready', 'paid', 'void')),
  bay             integer,
  payment_method  text check (payment_method in ('cash', 'card')),
  subtotal        numeric(10, 2) not null default 0,
  tax             numeric(10, 2) not null default 0,
  tax_rate        numeric(6, 5) not null default 0,
  total           numeric(10, 2) not null default 0,
  -- 'app' for tickets rung up here; 'datalube' for imported history (kept out of reports).
  source          text not null default 'app' check (source in ('app', 'datalube')),
  created_at      timestamptz not null default now(),
  started_at      timestamptz,
  finished_at     timestamptz,
  paid_at         timestamptz,
  voided_at       timestamptz
);

-- Two devices can't put two cars in the same bay.
create unique index if not exists tickets_one_car_per_bay
  on public.tickets (bay) where status in ('waiting', 'in_progress');
create index if not exists tickets_vehicle_history_idx
  on public.tickets (vehicle_id, paid_at desc) where status = 'paid';
create index if not exists tickets_paid_at_idx
  on public.tickets (paid_at) where status = 'paid';
create index if not exists tickets_open_idx
  on public.tickets (status) where status in ('waiting', 'in_progress', 'ready');

-- ---------------------------------------------------------------------------
-- Access rules
-- ---------------------------------------------------------------------------
alter table public.customers enable row level security;
alter table public.vehicles  enable row level security;
alter table public.tickets   enable row level security;

drop policy if exists "shop staff" on public.customers;
drop policy if exists "shop staff" on public.vehicles;
drop policy if exists "shop staff" on public.tickets;
create policy "shop staff" on public.customers for all to authenticated
  using (public.is_shop_user()) with check (public.is_shop_user());
create policy "shop staff" on public.vehicles for all to authenticated
  using (public.is_shop_user()) with check (public.is_shop_user());
create policy "shop staff" on public.tickets for all to authenticated
  using (public.is_shop_user()) with check (public.is_shop_user());

revoke all on public.customers, public.vehicles, public.tickets, public.shop_users from anon;
grant select, insert, update, delete on public.customers, public.vehicles, public.tickets to authenticated;
revoke all on function public.is_shop_user() from public, anon;
grant execute on function public.is_shop_user() to authenticated;
